const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  scan: () => ipcRenderer.invoke('sessions:scan'),
  rename: (id, name) => ipcRenderer.invoke('sessions:rename', id, name),
  usage: () => ipcRenderer.invoke('usage:get'),
  hide: (id) => ipcRenderer.invoke('sessions:hide', id),
  unhideAll: () => ipcRenderer.invoke('sessions:unhideAll'),
  hiddenCount: () => ipcRenderer.invoke('sessions:hiddenCount'),
  trash: (id) => ipcRenderer.invoke('sessions:trash', id),
  rest: (ids) => ipcRenderer.invoke('sessions:rest', ids),
  attachSkills: (id, skills) => ipcRenderer.invoke('sessions:attachSkills', id, skills),
  skills: (cwd) => ipcRenderer.invoke('skills:list', cwd),
  pinSkill: (id, on) => ipcRenderer.invoke('skills:pin', id, on),
  skillsMessage: (skills) => ipcRenderer.invoke('skills:message', skills),
  pickFolder: () => ipcRenderer.invoke('dialog:folder'),
  showMain: (id) => ipcRenderer.send('app:showMain', id),
  setWidget: (on) => ipcRenderer.send('widget:set', on),
  widgetEnabled: () => ipcRenderer.invoke('widget:get'),
  onWidgetState: (cb) => ipcRenderer.on('widget:state', (_e, on) => cb(on)),
  onSelect: (cb) => ipcRenderer.on('app:select', (_e, id) => cb(id)),
  onSessions: (cb) => ipcRenderer.on('sessions:update', (_e, list) => cb(list)),
  openFolder: (p) => ipcRenderer.send('shell:open', p),
  termOpen: (opts) => ipcRenderer.invoke('term:open', opts),
  termWrite: (id, data) => ipcRenderer.send('term:write', id, data),
  termResize: (id, cols, rows) => ipcRenderer.send('term:resize', id, cols, rows),
  termKill: (id) => ipcRenderer.send('term:kill', id),
  onTermData: (cb) => ipcRenderer.on('term:data', (_e, id, data) => cb(id, data)),
  onTermExit: (cb) => ipcRenderer.on('term:exit', (_e, id, code) => cb(id, code)),
});
